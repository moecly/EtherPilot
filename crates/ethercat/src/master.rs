/// Size of the process-data buffer handed to `ecx_config_map_group`. Must outlive `ecx_close`.
const IOMAP_SIZE: usize = 64 * 1024;

// SOEM enum constants are generated by bindgen as `<enum>_<VARIANT>`; alias them to the bare names
// used throughout this module.
const EC_STATE_NONE: u16 = soem_sys::ec_state_EC_STATE_NONE as u16;
const EC_STATE_INIT: u16 = soem_sys::ec_state_EC_STATE_INIT as u16;
const EC_STATE_PRE_OP: u16 = soem_sys::ec_state_EC_STATE_PRE_OP as u16;
const EC_STATE_SAFE_OP: u16 = soem_sys::ec_state_EC_STATE_SAFE_OP as u16;
const EC_STATE_OPERATIONAL: u16 = soem_sys::ec_state_EC_STATE_OPERATIONAL as u16;
const EC_STATE_ACK: u16 = soem_sys::ec_state_EC_STATE_ACK as u16;
const EC_STATE_ERROR: u16 = soem_sys::ec_state_EC_STATE_ERROR as u16;

/// SM "enable" flag as SOEM programs it (`~EC_SMENABLEMASK` in `ec_config.c`). SOEM stores SM flags
/// in host order, so no byte swap is needed here.
const SM_ENABLE_FLAG: u32 = 0x0000_8000;

/// CoE SDO abort "object does not exist"; used to treat absent optional objects as empty.
const SDO_ABORT_OBJECT_NOT_EXIST: u32 = 0x0602_0000;

const TIMEOUT_RET_US: i32 = soem_sys::EC_TIMEOUTRET as i32;
const TIMEOUT_STATE_US: i32 = soem_sys::EC_TIMEOUTSTATE as i32;

/// Default SDO transaction timeout, overridable via `ECAT_SDO_TIMEOUT_US` (clamped).
const SDO_TIMEOUT_DEFAULT_US: i32 = 100_000;
/// Wall-clock budget for a single multi-transaction request (OD/PDO walk).
const REQUEST_BUDGET_US: u64 = 200_000;
/// Wall-clock budget for one recovery pass.
const RECOVERY_PASS_BUDGET_US: u64 = 50_000;
/// Minimum gap between automatic recovery passes (skipped while the group asks for a check).
const RECOVERY_PASS_INTERVAL_US: u64 = 100_000;
/// Consecutive short-WKC cycles that trigger an automatic recovery pass.
const WKC_SHORT_TRIGGER: u32 = 3;
/// Back-off after a failed recover/reconfig, per slave.
const RECOVERY_BACKOFF_US: u64 = 2_000_000;
/// How long the IPC side waits for a request reply before giving up.
pub const REQUEST_RECV_TIMEOUT: std::time::Duration = std::time::Duration::from_secs(10);
/// Process-data capture cadence, aligned with the slave-state refresh.
const PROCESS_DATA_INTERVAL_CYCLES: u64 = 100;

/// Read `ECAT_SDO_TIMEOUT_US`, clamped to a sane range. Parse failures fall back silently.
fn read_sdo_timeout() -> i32 {
    std::env::var("ECAT_SDO_TIMEOUT_US")
        .ok()
        .and_then(|v| v.parse::<i32>().ok())
        .map(|v| v.clamp(10_000, 1_000_000))
        .unwrap_or(SDO_TIMEOUT_DEFAULT_US)
}

fn now_us() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_micros() as u64)
        .unwrap_or(0)
}

