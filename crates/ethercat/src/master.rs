//! The EtherCAT master engine: a single dedicated thread that owns the SOEM context and drives the
//! process-data cycle, plus a lock-free `SharedState` that the IPC side samples.

use std::ffi::{CStr, CString};
use std::sync::atomic::{AtomicBool, AtomicI32, AtomicI64, AtomicU64, Ordering};
use std::sync::mpsc::Sender;
use std::sync::Arc;
use std::thread::JoinHandle;
use std::time::{SystemTime, UNIX_EPOCH};

use parking_lot::Mutex;

use crate::error::EthercatError;
use crate::rt;
use crate::types::{AlState, CycleStats, EngineEvent, EngineLog, EngineState, LogLevel, SlaveInfo};

/// Size of the process-data buffer handed to `ecx_config_map_group`. Must outlive `ecx_close`.
const IOMAP_SIZE: usize = 64 * 1024;

// SOEM enum constants are generated by bindgen as `<enum>_<VARIANT>`; alias them to the bare names
// used throughout this module.
const EC_STATE_INIT: u16 = soem_sys::ec_state_EC_STATE_INIT as u16;
const EC_STATE_SAFE_OP: u16 = soem_sys::ec_state_EC_STATE_SAFE_OP as u16;
const EC_STATE_OPERATIONAL: u16 = soem_sys::ec_state_EC_STATE_OPERATIONAL as u16;
const EC_STATE_ERROR: u16 = soem_sys::ec_state_EC_STATE_ERROR as u16;

const TIMEOUT_RET_US: i32 = soem_sys::EC_TIMEOUTRET as i32;
const TIMEOUT_STATE_US: i32 = soem_sys::EC_TIMEOUTSTATE as i32;

fn now_us() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_micros() as u64)
        .unwrap_or(0)
}

#[derive(Debug, Clone)]
pub struct MasterConfig {
    pub iface: String,
    pub cycle_us: u32,
    pub rt_priority: i32,
}

/// Meta fields written once the session reaches `Running`; guarded so the IPC side can read them
/// without touching SOEM state.
#[derive(Debug, Clone)]
pub struct CycleMeta {
    pub state: EngineState,
    pub iface: Option<String>,
    pub cycle_us: u32,
    pub group0_input_bytes: u32,
    pub group0_output_bytes: u32,
    pub segments: u16,
}

impl Default for CycleMeta {
    fn default() -> Self {
        CycleMeta {
            state: EngineState::Idle,
            iface: None,
            cycle_us: 0,
            group0_input_bytes: 0,
            group0_output_bytes: 0,
            segments: 0,
        }
    }
}

/// Sampled by the IPC side only; the cycle thread never allocates or locks here.
pub struct SharedState {
    pub cycle_index: AtomicU64,
    pub wkc: AtomicI32,
    pub expected_wkc: AtomicI32,
    pub cycle_time_us: AtomicI64,
    pub jitter_us: AtomicI64,
    pub dc_time_ns: AtomicI64,
    pub lost_frames: AtomicU64,
    pub min_cycle_us: AtomicI64,
    pub max_cycle_us: AtomicI64,
    pub sum_cycle_us: AtomicI64,
    pub updated_at_us: AtomicU64,
    pub slaves: Mutex<Vec<SlaveInfo>>,
    pub meta: Mutex<CycleMeta>,
}

impl Default for SharedState {
    fn default() -> Self {
        SharedState {
            cycle_index: AtomicU64::new(0),
            wkc: AtomicI32::new(0),
            expected_wkc: AtomicI32::new(0),
            cycle_time_us: AtomicI64::new(0),
            jitter_us: AtomicI64::new(0),
            dc_time_ns: AtomicI64::new(0),
            lost_frames: AtomicU64::new(0),
            min_cycle_us: AtomicI64::new(0),
            max_cycle_us: AtomicI64::new(0),
            sum_cycle_us: AtomicI64::new(0),
            updated_at_us: AtomicU64::new(0),
            slaves: Mutex::new(Vec::new()),
            meta: Mutex::new(CycleMeta::default()),
        }
    }
}

impl SharedState {
    pub fn snapshot(&self) -> crate::types::MasterSnapshot {
        let meta = self.meta.lock().clone();
        let slaves = self.slaves.lock().clone();
        let cycles = self.cycle_index.load(Ordering::Relaxed);
        let (min, max, avg) = if cycles == 0 {
            (0, 0, 0)
        } else {
            (
                self.min_cycle_us.load(Ordering::Relaxed),
                self.max_cycle_us.load(Ordering::Relaxed),
                self.sum_cycle_us.load(Ordering::Relaxed) / cycles as i64,
            )
        };

        crate::types::MasterSnapshot {
            state: meta.state,
            iface: meta.iface,
            cycle_us: meta.cycle_us,
            slave_count: slaves.len() as i32,
            group0_input_bytes: meta.group0_input_bytes,
            group0_output_bytes: meta.group0_output_bytes,
            segments: meta.segments,
            slaves,
            cycle: CycleStats {
                cycle_index: cycles,
                wkc: self.wkc.load(Ordering::Relaxed),
                expected_wkc: self.expected_wkc.load(Ordering::Relaxed),
                wkc_ok: self.wkc.load(Ordering::Relaxed)
                    >= self.expected_wkc.load(Ordering::Relaxed),
                cycle_time_us: self.cycle_time_us.load(Ordering::Relaxed),
                jitter_us: self.jitter_us.load(Ordering::Relaxed),
                dc_time_ns: self.dc_time_ns.load(Ordering::Relaxed),
                lost_frames: self.lost_frames.load(Ordering::Relaxed),
                min_cycle_us: min,
                max_cycle_us: max,
                avg_cycle_us: avg,
            },
            updated_at_us: self.updated_at_us.load(Ordering::Relaxed),
        }
    }
}

/// Copy a `char[N]` SOEM field into an owned `String`. Never retains the pointer.
unsafe fn c_str_from_array(buf: &[std::os::raw::c_char]) -> String {
    let p = buf.as_ptr();
    if p.is_null() {
        return String::new();
    }
    CStr::from_ptr(p).to_string_lossy().into_owned()
}

/// Map SOEM's `slavelist` into `SlaveInfo`s. Index 0 (virtual broadcast slave) is excluded.
fn map_slaves(ctx: &soem_sys::ecx_contextt) -> Vec<SlaveInfo> {
    let count = ctx.slavecount.max(0) as usize;
    let max = ctx.slavelist.len().saturating_sub(1);
    let mut out = Vec::with_capacity(count.min(max));
    for i in 1..=count.min(max) {
        let s = &ctx.slavelist[i];
        // SAFETY: `s.name` is a null-terminated char array; `ec_ALstatuscode2string` returns a
        // pointer to a static string that is copied immediately.
        let (name, al_status_text) = unsafe {
            (
                c_str_from_array(&s.name),
                CStr::from_ptr(soem_sys::ec_ALstatuscode2string(s.ALstatuscode))
                    .to_string_lossy()
                    .into_owned(),
            )
        };
        let al_state_raw = s.state;
        out.push(SlaveInfo {
            position: i as u16,
            name,
            config_addr: s.configadr,
            alias: s.aliasadr,
            vendor_id: s.eep_man,
            product_code: s.eep_id,
            revision: s.eep_rev,
            serial: s.eep_ser,
            al_state_raw,
            al_state: AlState::from_raw(al_state_raw),
            al_state_error: al_state_raw & EC_STATE_ERROR != 0,
            al_status_code: s.ALstatuscode,
            al_status_text,
            input_bits: s.Ibits,
            output_bits: s.Obits,
            input_bytes: s.Ibytes,
            output_bytes: s.Obytes,
            has_dc: s.hasdc != 0,
            is_lost: s.islost != 0,
            topology: s.topology,
            active_ports: s.activeports,
            group: s.group,
            parent: s.parent,
            parent_port: s.parentport,
            entry_port: s.entryport,
        });
    }
    out
}

/// Build a human-readable report of every non-OPERATIONAL slave after a failed transition.
unsafe fn describe_failed_slaves(ctx: *mut soem_sys::ecx_contextt) -> String {
    soem_sys::ecx_readstate(ctx);
    let c = &*ctx;
    let count = c.slavecount.max(0) as usize;
    let max = c.slavelist.len().saturating_sub(1);
    let mut parts = Vec::new();
    for i in 1..=count.min(max) {
        let s = &c.slavelist[i];
        if s.state & 0x0f != EC_STATE_OPERATIONAL {
            let text = CStr::from_ptr(soem_sys::ec_ALstatuscode2string(s.ALstatuscode))
                .to_string_lossy()
                .into_owned();
            parts.push(format!(
                "slave {i} state 0x{:04X} AL 0x{:04X} {}",
                s.state, s.ALstatuscode, text
            ));
        }
    }
    parts.join("; ")
}

pub struct Master {
    stop: Arc<AtomicBool>,
    handle: Option<JoinHandle<()>>,
    shared: Arc<SharedState>,
}

impl Master {
    pub fn start(cfg: MasterConfig, log_tx: Sender<EngineEvent>) -> Result<Master, EthercatError> {
        let shared = Arc::new(SharedState::default());
        let stop = Arc::new(AtomicBool::new(false));
        let (ready_tx, ready_rx) = std::sync::mpsc::channel::<Result<(), EthercatError>>();

        let thread_stop = stop.clone();
        let thread_shared = shared.clone();
        let handle = std::thread::Builder::new()
            .name("ecat-cycle".into())
            .stack_size(1 << 20)
            .spawn(move || engine(cfg, thread_shared, thread_stop, log_tx, ready_tx))
            .map_err(|_| EthercatError::ThreadStart)?;

        match ready_rx.recv() {
            Ok(Ok(())) => Ok(Master {
                stop,
                handle: Some(handle),
                shared,
            }),
            Ok(Err(err)) => {
                let _ = handle.join();
                Err(err)
            }
            Err(_) => {
                let _ = handle.join();
                Err(EthercatError::ThreadStart)
            }
        }
    }

    pub fn shared(&self) -> Arc<SharedState> {
        self.shared.clone()
    }

    pub fn stop(mut self) -> Result<(), EthercatError> {
        self.shutdown()
    }

    fn shutdown(&mut self) -> Result<(), EthercatError> {
        self.stop.store(true, Ordering::SeqCst);
        if let Some(handle) = self.handle.take() {
            handle.join().map_err(|_| EthercatError::Join)?;
        }
        Ok(())
    }
}

impl Drop for Master {
    fn drop(&mut self) {
        let _ = self.shutdown();
    }
}

/// Engine thread body. Pre-handshake failures are reported over `ready_tx`; runtime events over
/// `log_tx`.
fn engine(
    cfg: MasterConfig,
    shared: Arc<SharedState>,
    stop: Arc<AtomicBool>,
    log_tx: Sender<EngineEvent>,
    ready_tx: Sender<Result<(), EthercatError>>,
) {
    let log = |level: LogLevel, message: String| {
        let _ = log_tx.send(EngineEvent::Log(EngineLog {
            at_us: now_us(),
            level,
            message,
        }));
    };

    match rt::promote_current_thread(cfg.rt_priority) {
        Ok(()) => log(
            LogLevel::Info,
            format!("real-time: SCHED_FIFO priority {}", cfg.rt_priority),
        ),
        Err((prio, e)) => log(
            LogLevel::Warn,
            format!("real-time: SCHED_FIFO priority {prio} unavailable ({e}); using SCHED_OTHER"),
        ),
    }
    if let Err(e) = rt::lock_memory() {
        log(
            LogLevel::Warn,
            format!("real-time: mlockall failed ({e}); memory may be paged"),
        );
    }

    // The context and IOmap must stay alive and unmoved until after `ecx_close`.
    let mut ctx = soem_sys::context_new();
    let ctx_ptr: *mut soem_sys::ecx_contextt = &mut *ctx;
    let mut iomap: Box<[u8; IOMAP_SIZE]> = Box::new([0u8; IOMAP_SIZE]);

    let iface_c = CString::new(cfg.iface.as_str()).expect("interface name contains a NUL byte");
    // SAFETY: `ctx_ptr` is a valid, live context; `iface_c` outlives the call.
    let init_rc = unsafe { soem_sys::ecx_init(ctx_ptr, iface_c.as_ptr()) };
    if init_rc <= 0 {
        let err = std::io::Error::last_os_error();
        let e = EthercatError::SocketInit {
            iface: cfg.iface.clone(),
            os_error: err.raw_os_error(),
        };
        let _ = ready_tx.send(Err(e));
        return;
    }

    // SAFETY: all SOEM calls below use the live `ctx_ptr` and a valid `iomap`.
    let slavecount = unsafe { soem_sys::ecx_config_init(ctx_ptr) };
    if slavecount <= 0 {
        unsafe { soem_sys::ecx_close(ctx_ptr) };
        let _ = ready_tx.send(Err(EthercatError::NoSlaves {
            iface: cfg.iface.clone(),
        }));
        return;
    }

    unsafe {
        soem_sys::ecx_config_map_group(ctx_ptr, iomap.as_mut_ptr().cast(), 0);
        soem_sys::ecx_configdc(ctx_ptr);
        soem_sys::ecx_statecheck(ctx_ptr, 0, EC_STATE_SAFE_OP, TIMEOUT_STATE_US * 4);
        soem_sys::ecx_send_processdata(ctx_ptr);
        soem_sys::ecx_receive_processdata(ctx_ptr, TIMEOUT_RET_US);
        (*ctx_ptr).slavelist[0].state = EC_STATE_OPERATIONAL;
        soem_sys::ecx_writestate(ctx_ptr, 0);

        let mut reached = false;
        for _ in 0..10 {
            soem_sys::ecx_send_processdata(ctx_ptr);
            soem_sys::ecx_receive_processdata(ctx_ptr, TIMEOUT_RET_US);
            if soem_sys::ecx_statecheck(ctx_ptr, 0, EC_STATE_OPERATIONAL, TIMEOUT_STATE_US / 10)
                == EC_STATE_OPERATIONAL
            {
                reached = true;
                break;
            }
        }

        if !reached {
            let details = describe_failed_slaves(ctx_ptr);
            for line in details.split("; ").filter(|l| !l.is_empty()) {
                log(LogLevel::Error, line.to_string());
            }
            (*ctx_ptr).slavelist[0].state = EC_STATE_INIT;
            soem_sys::ecx_writestate(ctx_ptr, 0);
            soem_sys::ecx_close(ctx_ptr);
            let _ = ready_tx.send(Err(EthercatError::Config(if details.is_empty() {
                "slaves did not reach OPERATIONAL".to_string()
            } else {
                details
            })));
            return;
        }
    }

    let slaves = {
        // SAFETY: the context is initialised and mapped.
        let c = unsafe { &*ctx_ptr };
        map_slaves(c)
    };
    {
        let g0 = &unsafe { &*ctx_ptr }.grouplist[0];
        let mut meta = shared.meta.lock();
        meta.state = EngineState::Running;
        meta.iface = Some(cfg.iface.clone());
        meta.cycle_us = cfg.cycle_us;
        meta.group0_output_bytes = g0.Obytes;
        meta.group0_input_bytes = g0.Ibytes;
        meta.segments = g0.nsegments;
    }
    *shared.slaves.lock() = slaves;
    log(
        LogLevel::Info,
        format!(
            "connected: {} slaves, {}O+{}I bytes in {} segments",
            slavecount,
            unsafe { (*ctx_ptr).grouplist[0].Obytes },
            unsafe { (*ctx_ptr).grouplist[0].Ibytes },
            unsafe { (*ctx_ptr).grouplist[0].nsegments },
        ),
    );
    let _ = ready_tx.send(Ok(()));

    // --- Cycle loop ---
    let period_ns: i64 = cfg.cycle_us as i64 * 1000;
    let mut use_usleep = false;
    let mut usleep_warned = false;
    let mut cycles: u64 = 0;
    let mut min_cycle = i64::MAX;
    let mut max_cycle = i64::MIN;
    let mut sum_cycle: i64 = 0;
    let mut lost: u64 = 0;

    while !stop.load(Ordering::SeqCst) {
        let mut t0 = unsafe { soem_sys::osal_current_time() };
        unsafe { soem_sys::ecx_send_processdata(ctx_ptr) };
        let wkc = unsafe { soem_sys::ecx_receive_processdata(ctx_ptr, TIMEOUT_RET_US) };
        let mut t1 = unsafe { soem_sys::osal_current_time() };
        let mut diff: soem_sys::timespec = unsafe { std::mem::zeroed() };
        unsafe { soem_sys::osal_time_diff(&mut t0, &mut t1, &mut diff) };

        let cycle_time_us = diff.tv_sec * 1_000_000 + diff.tv_nsec / 1_000;
        let jitter_us = cycle_time_us - cfg.cycle_us as i64;

        let (expected_wkc, dc_time_ns) = {
            let c = unsafe { &*ctx_ptr };
            let g = &c.grouplist[0];
            (g.outputsWKC as i32 * 2 + g.inputsWKC as i32, c.DCtime)
        };
        if wkc < expected_wkc {
            lost += 1;
        }

        cycles += 1;
        if cycle_time_us < min_cycle {
            min_cycle = cycle_time_us;
        }
        if cycle_time_us > max_cycle {
            max_cycle = cycle_time_us;
        }
        sum_cycle += cycle_time_us;

        shared.cycle_index.store(cycles, Ordering::Relaxed);
        shared.wkc.store(wkc, Ordering::Relaxed);
        shared.expected_wkc.store(expected_wkc, Ordering::Relaxed);
        shared.cycle_time_us.store(cycle_time_us, Ordering::Relaxed);
        shared.jitter_us.store(jitter_us, Ordering::Relaxed);
        shared.dc_time_ns.store(dc_time_ns, Ordering::Relaxed);
        shared.lost_frames.store(lost, Ordering::Relaxed);
        shared.min_cycle_us.store(min_cycle, Ordering::Relaxed);
        shared.max_cycle_us.store(max_cycle, Ordering::Relaxed);
        shared.sum_cycle_us.store(sum_cycle, Ordering::Relaxed);
        shared.updated_at_us.store(now_us(), Ordering::Relaxed);

        if cycles.is_multiple_of(100) {
            let slaves = {
                unsafe { soem_sys::ecx_readstate(ctx_ptr) };
                let c = unsafe { &*ctx_ptr };
                map_slaves(c)
            };
            *shared.slaves.lock() = slaves;
        }

        if use_usleep {
            unsafe { soem_sys::osal_usleep(cfg.cycle_us) };
        } else {
            let mut ts: soem_sys::timespec = unsafe { std::mem::zeroed() };
            unsafe { soem_sys::osal_get_monotonic_time(&mut ts) };
            ts.tv_nsec += period_ns;
            if ts.tv_nsec >= 1_000_000_000 {
                ts.tv_sec += 1;
                ts.tv_nsec -= 1_000_000_000;
            }
            if unsafe { soem_sys::osal_monotonic_sleep(&mut ts) } == -1 {
                if !usleep_warned {
                    usleep_warned = true;
                    log(
                        LogLevel::Warn,
                        "osal_monotonic_sleep unavailable; falling back to osal_usleep".to_string(),
                    );
                }
                use_usleep = true;
                unsafe { soem_sys::osal_usleep(cfg.cycle_us) };
            }
        }
    }

    // --- Shutdown: return every slave to INIT, then close the socket. ---
    unsafe {
        (*ctx_ptr).slavelist[0].state = EC_STATE_INIT;
        soem_sys::ecx_writestate(ctx_ptr, 0);
        soem_sys::ecx_close(ctx_ptr);
    }
    let _ = log_tx.send(EngineEvent::Stopped {
        reason: "disconnected".to_string(),
    });
    // `ctx` and `iomap` are dropped here, after `ecx_close` has returned.
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::types::AlState;

    fn write_name(buf: &mut [std::os::raw::c_char], name: &str) {
        let bytes = name.as_bytes();
        let n = bytes.len().min(buf.len() - 1);
        for (i, b) in bytes[..n].iter().enumerate() {
            buf[i] = *b as std::os::raw::c_char;
        }
        buf[n] = 0;
    }

    #[test]
    fn maps_slave_fields_and_snapshot() {
        let mut ctx = soem_sys::context_new();
        ctx.slavecount = 2;

        {
            let s = &mut ctx.slavelist[1];
            write_name(&mut s.name, "Coupler");
            s.configadr = 0x1001;
            s.aliasadr = 7;
            s.eep_man = 0x0000_0002;
            s.eep_id = 0x0abc_def0;
            s.eep_rev = 0x0011_0000;
            s.state = EC_STATE_SAFE_OP | EC_STATE_ERROR;
            s.ALstatuscode = 0x0011;
            s.Ibits = 16;
            s.Obits = 8;
            s.parent = 0;
            s.parentport = 0;
            s.entryport = 1;
            s.hasdc = 1;
        }
        {
            let s = &mut ctx.slavelist[2];
            write_name(&mut s.name, "Terminal");
            s.state = EC_STATE_OPERATIONAL;
            s.parent = 1;
            s.parentport = 1;
            s.entryport = 0;
        }
        ctx.grouplist[0].Obytes = 4;
        ctx.grouplist[0].Ibytes = 8;
        ctx.grouplist[0].nsegments = 1;

        let slaves = map_slaves(&ctx);
        assert_eq!(slaves.len(), 2);

        let first = &slaves[0];
        assert_eq!(first.position, 1);
        assert_eq!(first.name, "Coupler");
        assert_eq!(first.al_state, AlState::SafeOp);
        assert!(first.al_state_error);
        assert_eq!(first.al_state_raw, EC_STATE_SAFE_OP | EC_STATE_ERROR);
        assert_eq!(first.vendor_id, 0x0000_0002);
        assert_eq!(first.product_code, 0x0abc_def0);
        assert_eq!(first.alias, 7);
        assert_eq!(first.parent, 0);
        assert_eq!(first.entry_port, 1);
        assert!(first.has_dc);
        assert!(!first.al_status_text.is_empty());

        let second = &slaves[1];
        assert_eq!(second.position, 2);
        assert_eq!(second.al_state, AlState::Operational);
        assert!(!second.al_state_error);
        assert_eq!(second.parent, 1);
        assert_eq!(second.parent_port, 1);

        let shared = SharedState::default();
        shared.slaves.lock().extend(slaves);
        {
            let mut meta = shared.meta.lock();
            meta.state = EngineState::Running;
            meta.iface = Some("eth0".to_string());
            meta.cycle_us = 1000;
            meta.group0_input_bytes = 8;
            meta.group0_output_bytes = 4;
            meta.segments = 1;
        }
        shared.cycle_index.store(3, Ordering::Relaxed);
        shared.sum_cycle_us.store(3300, Ordering::Relaxed);
        shared.min_cycle_us.store(1050, Ordering::Relaxed);
        shared.max_cycle_us.store(1150, Ordering::Relaxed);

        let snap = shared.snapshot();
        assert_eq!(snap.state, EngineState::Running);
        assert_eq!(snap.slave_count, 2);
        assert_eq!(snap.iface.as_deref(), Some("eth0"));
        assert_eq!(snap.slaves[0].parent, 0);
        assert_eq!(snap.cycle.cycle_index, 3);
        assert_eq!(snap.cycle.avg_cycle_us, 1100);
        assert_eq!(snap.cycle.min_cycle_us, 1050);
    }
}
