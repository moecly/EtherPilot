//! The EtherCAT master engine: a single dedicated thread that owns the SOEM context and drives the
//! process-data cycle, plus a lock-free `SharedState` that the IPC side samples.
//!
//! Between two process-data cycles the thread also drains a request channel (SDO/OD/PDO access,
//! manual recovery) and, when the work counter shows trouble, runs one bounded recovery pass in the
//! spirit of SOEM's `ec_sample`.

