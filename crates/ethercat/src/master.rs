        shared.sum_cycle_us.store(3300, Ordering::Relaxed);
        shared.min_cycle_us.store(1050, Ordering::Relaxed);
        shared.max_cycle_us.store(1150, Ordering::Relaxed);
        shared.bus_lost.store(1, Ordering::Relaxed);
        shared.bus_acks.store(2, Ordering::Relaxed);

